// ------------------------- Cache Expiration Policies ------------------------
const app_cache_expiration = new ExpirationPlugin({
  maxEntries: 100, // Maximum number of entries to keep
  maxAgeSeconds: APP_CONFIG.caching.expirations.app,
  purgeOnQuotaError: true, // Delete cache if storage quota exceeded
})

const api_cache_expiration = new ExpirationPlugin({
  maxEntries: 100, // Maximum number of entries to keep
  maxAgeSeconds: APP_CONFIG.caching.expirations.api,
  purgeOnQuotaError: true, // Delete cache if storage quota exceeded
})

const image_cache_expiration = new ExpirationPlugin({
  maxEntries: 1000, // Maximum number of entries to keep
  maxAgeSeconds: APP_CONFIG.caching.expirations.images,
  purgeOnQuotaError: true, // Delete cache if storage quota exceeded
})

// ----------------------------------------
// Workbox app shell, originally generated by create-react-app
// ----------------------------------------
clientsClaim()

// Precache all of the assets generated by the build process.
const allPrecacheEntries: PrecacheEntry[] = [
  ...self.__WB_MANIFEST.map((entry) =>
    typeof entry === 'string' ? { revision: null, url: entry } : entry
  ),
  ...PUBLIC_ASSETS_IMAGES.map((image) => ({
    revision: null,
    url: `/assets/images/${image}`,
  })),
  ...ROOT_STATIC.map((file) => ({ revision: null, url: `/${file}` })),
  {
    revision: null,
    url: 'https://cdn.lawrencemcdaniel.com/lawrencemcdaniel-headshot-square.jpeg',
  },
]

// Deduplicate by URL (ignoring ?__WB_REVISION__)
const manifestMap = new Map<string, PrecacheEntry>()
allPrecacheEntries.forEach((entry) => {
  const url = entry.url.split('?__WB_REVISION__=')[0]
  manifestMap.set(url, entry) // Keeps the last revision for each URL
})

const dedupedManifest = Array.from(manifestMap.values())

precacheAndRoute(dedupedManifest)

// Every page is its own html file, which the build prerenders with the page's
// content and data (src/prerender/). So a navigation fetches its page from the
// network, and keeps a copy for offline use. Offline, a page that was never
// visited gets the home page (index.html, precached), and the app renders the
// page that was asked for.
const pages = new NetworkFirst({
  cacheName: APP_CONFIG.caching.names.pages,
  networkTimeoutSeconds: 5,
  plugins: [new CacheableResponsePlugin({ statuses: [200] })],
})
const offlineFallback = createHandlerBoundToURL(import.meta.env.BASE_URL + 'index.html')
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$')
registerRoute(
  // Return false to exempt requests that aren't for a page.
  ({ request, url }) => {
    // If this isn't a navigation, skip.
    if (request.mode !== 'navigate') {
      return false
    } // If this is a URL that starts with /_, skip.

    if (url.pathname.startsWith('/_')) {
      return false
    } // If this looks like a URL for a resource, because it contains // a file extension, skip.

    if (url.pathname.match(fileExtensionRegexp)) {
      return false
    } // Return true to signal that we want to use the handler.

    return true
  },
  async (options) => {
    try {
      return await pages.handle(options)
    } catch {
      return offlineFallback(options)
    }
  }
)

// This allows the web app to trigger skipWaiting via
// registration.waiting.postMessage({type: 'SKIP_WAITING'})
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting()
  }
})
self.addEventListener('install', () => {
  self.skipWaiting()
})

// Cleanup old caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames
          .filter(
            (name) =>
              !(Object.values(APP_CONFIG.caching.names) as string[]).includes(name) &&
              !name.startsWith('workbox-precache')
          )
          .map((name) => caches.delete(name))
      )
    })
  )
})

