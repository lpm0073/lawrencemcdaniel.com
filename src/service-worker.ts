clientsClaim()

// Precache all of the assets generated by the build process.
const allPrecacheEntries: PrecacheEntry[] = [
  ...self.__WB_MANIFEST.map((entry) =>
    typeof entry === 'string' ? { revision: null, url: entry } : entry
  ),
  ...PUBLIC_ASSETS_IMAGES.map((image) => ({
    revision: null,
    url: `/assets/images/${image}`,
  })),
  ...ROOT_STATIC.map((file) => ({ revision: null, url: `/${file}` })),
  {
    revision: null,
    url: 'https://cdn.lawrencemcdaniel.com/lawrencemcdaniel-headshot-square.jpeg',
  },
]

// Deduplicate by URL (ignoring ?__WB_REVISION__)
const manifestMap = new Map<string, PrecacheEntry>()
allPrecacheEntries.forEach((entry) => {
  const url = entry.url.split('?__WB_REVISION__=')[0]
  manifestMap.set(url, entry) // Keeps the last revision for each URL
})

const dedupedManifest = Array.from(manifestMap.values())

precacheAndRoute(dedupedManifest)

// Set up App Shell-style routing, so that all navigation requests
// are fulfilled with the index.html shell. Learn more at
// https://developers.google.com/web/fundamentals/architecture/app-shell
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$')
registerRoute(
  // Return false to exempt requests from being fulfilled by index.html.
  ({ request, url }) => {
    // If this isn't a navigation, skip.
    if (request.mode !== 'navigate') {
      return false
    } // If this is a URL that starts with /_, skip.

    if (url.pathname.startsWith('/_')) {
      return false
    } // If this looks like a URL for a resource, because it contains // a file extension, skip.

    if (url.pathname.match(fileExtensionRegexp)) {
      return false
    } // Return true to signal that we want to use the handler.

    return true
  },
  createHandlerBoundToURL(import.meta.env.BASE_URL + 'index.html')
)

// This allows the web app to trigger skipWaiting via
// registration.waiting.postMessage({type: 'SKIP_WAITING'})
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting()
  }
})
self.addEventListener('install', () => {
  self.skipWaiting()
})

// Cleanup old caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames
          .filter(
            (name) =>
              !(Object.values(APP_CONFIG.caching.names) as string[]).includes(name) &&
              !name.startsWith('workbox-precache')
          )
          .map((name) => caches.delete(name))
      )
    })
  )
})

